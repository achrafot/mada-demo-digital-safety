from docx import Document
from docx.shared import Pt, Cm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

MAROON_HX = '8B1A2E'
DARK_GRAY  = RGBColor(0x2D, 0x2D, 0x2D)
GOLD       = RGBColor(0xC9, 0xA8, 0x4C)

def rtl(para):
    pPr = para._p.get_or_add_pPr()
    bidi = OxmlElement('w:bidi')
    pPr.insert(0, bidi)
    jc = OxmlElement('w:jc')
    jc.set(qn('w:val'), 'right')
    pPr.append(jc)

def set_cell_bg(cell, hex_color):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), hex_color)
    tcPr.append(shd)

def h1(doc, text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    rtl(p)
    r = p.add_run(text)
    r.bold = True; r.font.size = Pt(16)
    r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
    pPr = p._p.get_or_add_pPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), MAROON_HX)
    pPr.append(shd)
    p.paragraph_format.space_before = Pt(18)
    p.paragraph_format.space_after  = Pt(12)

def h2(doc, text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    rtl(p)
    r = p.add_run(text)
    r.bold = True; r.font.size = Pt(13)
    r.font.color.rgb = RGBColor(0x8B, 0x1A, 0x2E)
    pPr = p._p.get_or_add_pPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), 'F5F0E8')
    pPr.append(shd)
    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after  = Pt(6)

def h3(doc, text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    rtl(p)
    r = p.add_run(text)
    r.bold = True; r.font.size = Pt(11)
    r.font.color.rgb = RGBColor(0x8B, 0x1A, 0x2E)
    p.paragraph_format.space_before = Pt(8)
    p.paragraph_format.space_after  = Pt(4)

def body(doc, text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    rtl(p)
    r = p.add_run(text)
    r.font.size = Pt(11)
    r.font.color.rgb = DARK_GRAY
    p.paragraph_format.first_line_indent = Cm(0.75)
    p.paragraph_format.line_spacing = Pt(20)
    p.paragraph_format.space_after = Pt(8)

def bullet_item(doc, text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    rtl(p)
    r = p.add_run(f"◈  {text}")
    r.font.size = Pt(10.5)
    r.font.color.rgb = DARK_GRAY
    p.paragraph_format.right_indent = Cm(0.75)
    p.paragraph_format.space_after  = Pt(5)

def add_page_break(doc):
    p = doc.add_paragraph()
    pPr = p._p.get_or_add_pPr()
    pageBreak = OxmlElement('w:pageBreakBefore')
    pageBreak.set(qn('w:val'), '1')
    pPr.append(pageBreak)

